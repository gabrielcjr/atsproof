def get_article_by_slug(slug: str) -> Optional[Dict[str, Any]]:
    """Finds an article matching either its Portuguese or English slug."""
    clean_slug = (slug or "").strip().lower()
    for art in ARTICLES:
        if art["slug_pt"] == clean_slug or art["slug_en"] == clean_slug:
            return art
    return None


